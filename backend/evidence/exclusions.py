"""Classify repository files the way GitHub Linguist does, so only code the
candidate could plausibly have written counts toward authorship.

Categories: source / vendored / generated / documentation / binary.
Only ``source`` counts. Rules are our own, modelled on Linguist's
vendor.yml / generated.rb / documentation.yml categories, and
``.gitattributes`` overrides (linguist-vendored, linguist-generated,
linguist-documentation, with ``-attr`` / ``!attr`` / ``attr=false`` to
unmark) are applied on top, later lines winning, as git does.
"""

from __future__ import annotations

import fnmatch
import re
from dataclasses import dataclass, field
from pathlib import PurePosixPath
from typing import Literal

Category = Literal["source", "vendored", "generated", "documentation", "binary"]

VENDORED_DIRS = {
    "node_modules", "vendor", "vendors", "venv", ".venv", "site-packages", "third_party",
    "third-party", "thirdparty", "bower_components", "Pods", "Carthage", "external", "deps",
    "__pycache__", ".tox", ".eggs",
}
BUILD_DIRS = {"dist", "build", "target", ".next", ".nuxt", "coverage", "__generated__", "generated"}
GENERATED_DIRS = {"migrations"}
DOC_DIRS = {"docs", "doc", "documentation", "Documentation"}

LOCK_FILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "npm-shrinkwrap.json", "poetry.lock", "Pipfile.lock",
    "Cargo.lock", "go.sum", "composer.lock", "Gemfile.lock", "mix.lock", "pubspec.lock", "uv.lock",
    "packages.lock.json", "flake.lock", "bun.lockb", "Podfile.lock",
}
GENERATED_PATTERNS = (
    "*.min.js", "*.min.css", "*.min.mjs", "*.map", "*_pb2.py", "*_pb2_grpc.py", "*_pb2.pyi", "*.pb.go",
    "*.pb.cc", "*.pb.h", "*.pb.swift", "*_grpc.pb.go", "*.pb.ts", "*_pb.js", "*_pb.d.ts", "*.designer.cs",
    "*.g.dart", "*.freezed.dart", "*.generated.*", "*.gen.go",
)
DOC_PATTERNS = (
    "*.md", "*.markdown", "*.rst", "*.adoc", "LICENSE*", "LICENCE*", "COPYING*", "CHANGELOG*",
    "CHANGES*", "HISTORY*", "AUTHORS*", "CONTRIBUTING*", "CODE_OF_CONDUCT*", "NOTICE*", "README*",
    ".gitattributes", ".mailmap",  # repository configuration: never credited as authored code
)
BINARY_EXTS = {
    # images / media
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".icns", ".tif", ".tiff", ".webp", ".svg", ".psd",
    ".ai", ".heic", ".mp3", ".wav", ".ogg", ".flac", ".m4a", ".aac", ".mp4", ".mov", ".avi", ".mkv",
    ".webm", ".wmv",
    # fonts
    ".ttf", ".otf", ".woff", ".woff2", ".eot",
    # archives / packages
    ".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".jar", ".war", ".whl", ".egg", ".deb",
    ".rpm", ".dmg", ".iso", ".apk", ".ipa",
    # compiled / object / data blobs
    ".exe", ".dll", ".so", ".dylib", ".a", ".o", ".obj", ".class", ".pyc", ".pyo", ".wasm", ".bin",
    ".dat", ".db", ".sqlite", ".sqlite3", ".pkl", ".pickle", ".npy", ".npz", ".h5", ".hdf5", ".onnx",
    ".pt", ".pth", ".ckpt", ".parquet", ".feather", ".tflite", ".mlmodel",
    # documents
    ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx", ".odt", ".ods", ".key", ".pages",
}
_GENERATED_MARKERS = re.compile(
    rb"(?i)(generated by|auto-?generated|do not edit|code generated .* do not edit|openapi-generator|swagger-codegen)"
)
LINGUIST_ATTRS = {"linguist-vendored": "vendored", "linguist-generated": "generated",
                  "linguist-documentation": "documentation"}


@dataclass
class AttrRule:
    pattern: str
    attrs: dict[str, bool]


@dataclass
class GitAttributes:
    rules: list[AttrRule] = field(default_factory=list)

    @classmethod
    def parse(cls, text: str) -> "GitAttributes":
        rules = []
        for raw in text.splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            pattern, attrs = parts[0], {}
            for tok in parts[1:]:
                if tok.startswith(("-", "!")):
                    name, val = tok[1:], False
                elif "=" in tok:
                    name, v = tok.split("=", 1)
                    val = v.strip().lower() not in ("false", "0", "no", "unset")
                else:
                    name, val = tok, True
                if name in LINGUIST_ATTRS:
                    attrs[name] = val
            if attrs:
                rules.append(AttrRule(pattern, attrs))
        return cls(rules)

    def overrides(self, path: str) -> dict[str, bool]:
        """Final linguist-* attribute values for ``path`` (later lines win)."""
        out: dict[str, bool] = {}
        for rule in self.rules:
            if _attr_match(rule.pattern, path):
                out.update(rule.attrs)
        return out


def _attr_match(pattern: str, path: str) -> bool:
    """gitattributes-style matching: patterns without '/' match the basename
    at any depth; patterns with '/' are anchored to the repo root; '**' spans dirs."""
    pat = pattern.lstrip("/")
    if pat.endswith("/"):
        pat += "**"
    if "/" not in pattern.rstrip("/"):
        return fnmatch.fnmatchcase(PurePosixPath(path).name, pat) or fnmatch.fnmatchcase(path, pat)
    if fnmatch.fnmatchcase(path, pat):
        return True
    if pat.endswith("/**"):
        return path.startswith(pat[:-3] + "/")
    return False


def _in_dir(parts: tuple[str, ...], names: set[str]) -> bool:
    return any(p in names for p in parts[:-1])


def classify(path: str, attrs: GitAttributes | None = None, head: bytes | None = None,
             is_binary: bool | None = None) -> Category:
    """Category for a repo-relative path. ``head`` (first bytes of the file)
    enables content checks; ``is_binary`` is git's own text/binary verdict."""
    p = PurePosixPath(path)
    name, parts = p.name, p.parts
    ext = p.suffix.lower()

    category: Category
    if is_binary or ext in BINARY_EXTS:
        category = "binary"
    elif _in_dir(parts, VENDORED_DIRS):
        category = "vendored"
    elif (name in LOCK_FILES or any(fnmatch.fnmatchcase(name, g) for g in GENERATED_PATTERNS)
          or _in_dir(parts, BUILD_DIRS) or _in_dir(parts, GENERATED_DIRS)
          or (head is not None and _GENERATED_MARKERS.search(head[:600]))):
        category = "generated"
    elif _in_dir(parts, DOC_DIRS) or any(fnmatch.fnmatchcase(name, g) for g in DOC_PATTERNS):
        category = "documentation"
    else:
        category = "source"

    if category == "binary" or attrs is None:
        return category
    ov = attrs.overrides(path)
    for attr, cat in LINGUIST_ATTRS.items():  # explicit marking wins
        if ov.get(attr) is True:
            return cat  # type: ignore[return-value]
    for attr, cat in LINGUIST_ATTRS.items():  # explicit unmarking restores source
        if ov.get(attr) is False and category == cat:
            return "source"
    return category
